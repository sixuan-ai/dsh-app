#!/usr/bin/env python3
"""Activate verified R2 mirrors for public release URLs, retaining origin files."""
import argparse
import json
from pathlib import Path
import re
import shlex
import subprocess

REMOTE = r'''
import datetime,hashlib,json,os,re,shutil,subprocess,sys,tempfile
from pathlib import Path
from urllib.parse import urlsplit
meta=json.load(sys.stdin);version=meta['version'];cdn=meta.get('cdnUrl')
assert re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+',version)
name='dsh-app-'+version+'.apk'
if cdn:
 assert re.fullmatch(r'https://[A-Za-z0-9.-]+/[A-Za-z0-9_./-]+',cdn) and cdn.endswith('/'+name)
 assert '..' not in cdn.split('/')[3:]
release=Path('/var/www/dsh-releases');public=Path('/var/www/dsh-releases-public')
current=json.loads((public/'latest.json').read_text())
assert all(current[k]==meta[k]for k in ('version','versionCode','sha256','size','url')),'Release changed while activating CDN'
if cdn:
 origin_host=urlsplit(current['url']).hostname;cdn_host=urlsplit(cdn).hostname
 assert cdn_host!=origin_host and not cdn_host.endswith('.'+origin_host),'Use a sibling/separate CDN hostname to suppress legacy account headers'
source=public/name
assert source.stat().st_size==meta['size'] and hashlib.sha256(source.read_bytes()).hexdigest()==meta['sha256']
site=Path('/etc/nginx/sites-enabled/dsh-sixuanai').resolve()
mapfile=Path('/etc/nginx/conf.d/xharness-release-cdn.conf')
indexfile=release/'cdn-index.json'
if not cdn and not mapfile.exists():
 print(json.dumps({'cdnUrl':None,'status':'origin-only'}));sys.exit(0)
paths=[site,mapfile,indexfile,release/'latest.json',public/'latest.json',public/'version.json']
backup=Path('/var/backups/xharness-releases')/('cdn-'+datetime.datetime.now().strftime('%Y%m%d-%H%M%S'));backup.mkdir(parents=True,exist_ok=True)
snapshot={p:(p.read_bytes()if p.exists()else None)for p in paths}
for p,data in snapshot.items():
 if data is not None:(backup/p.name).write_bytes(data)
def write(path,data):
 fd,tmp=tempfile.mkstemp(prefix='.cdn-',dir=path.parent)
 try:
  with os.fdopen(fd,'wb')as f:f.write(data);f.flush();os.fsync(f.fileno());os.fchmod(f.fileno(),0o644)
  os.replace(tmp,path)
 finally:
  if os.path.exists(tmp):os.unlink(tmp)
try:
 index=json.loads(indexfile.read_text())if indexfile.exists()else{}
 if cdn:index[name]=cdn
 else:index.pop(name,None)
 lines=['# Generated by xHarness publisher. Use ?origin=1 for the backup copy.', 'map $arg_origin $xharness_release_force_origin {', '    default "";', '    "1" "direct";', '}', 'map "$xharness_release_force_origin:$uri" $xharness_release_cdn_url {','    default "";']
 for file,url in sorted(index.items()):
  assert re.fullmatch(r'dsh-app-[0-9]+\.[0-9]+\.[0-9]+\.apk',file)
  assert re.fullmatch(r'https://[A-Za-z0-9.-]+/[A-Za-z0-9_./-]+',url) and url.endswith('/'+file)
  lines.append('    '+json.dumps(':/releases-public/'+file)+' '+json.dumps(url)+';')
 if cdn:lines.append('    ":/releases-public/dsh-app-latest.apk" '+json.dumps(cdn)+';')
 lines.append('}')
 write(mapfile,('\n'.join(lines)+'\n').encode())
 text=site.read_text();marker='if ($xharness_release_cdn_url != "")'
 if marker not in text:
  needle='    location /releases-public/ {\n'
  assert text.count(needle)==1,'Cannot locate the public release location'
  text=text.replace(needle,needle+'        # Public signed APKs: small redirect, bytes served by Cloudflare R2.\n        if ($xharness_release_cdn_url != "") {\n            return 302 $xharness_release_cdn_url;\n        }\n')
  write(site,text.encode())
 subprocess.run(['nginx','-t'],check=True,capture_output=True)
 write(indexfile,json.dumps(index,ensure_ascii=False,indent=2).encode())
 for p in (release/'latest.json',public/'latest.json',public/'version.json'):
  data=json.loads(p.read_text())
  if cdn:data['cdnUrl']=cdn
  else:data.pop('cdnUrl',None)
  write(p,json.dumps(data,ensure_ascii=False,indent=2).encode())
 subprocess.run(['systemctl','reload','nginx'],check=True,capture_output=True)
 print(json.dumps({'cdnUrl':cdn,'backup':str(backup),'redirects':len(index)+(1 if cdn else 0)}))
except Exception:
 for p,data in snapshot.items():
  if data is None:p.unlink(missing_ok=True)
  else:write(p,data)
 subprocess.run(['nginx','-t'],check=True,capture_output=True)
 subprocess.run(['systemctl','reload','nginx'],check=True,capture_output=True)
 raise
'''


def activate(server, metadata):
    cmd=['ssh','-T','-o','BatchMode=yes',server,'sudo -n python3 -c '+shlex.quote(REMOTE)]
    result=subprocess.run(cmd,input=json.dumps(metadata),text=True,capture_output=True,check=True)
    return json.loads(result.stdout)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--server',default='sx-server')
    parser.add_argument('--manifest',type=Path,required=True)
    args=parser.parse_args()
    print(json.dumps(activate(args.server,json.loads(args.manifest.read_text()))))


if __name__=='__main__':main()
